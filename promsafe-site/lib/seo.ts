import type {Metadata} from 'next';

export const SITE_NAME='PromSafe';
export const COMPANY_NAME='ООО «Промбезопасность Консалт»';
export const DEFAULT_SITE_URL='https://promsafe.ru';

export function getSiteUrl(){
  return (process.env.NEXT_PUBLIC_SITE_URL||DEFAULT_SITE_URL).replace(/\/$/,'');
}

export function absoluteUrl(path='/'){
  const base=getSiteUrl();
  if(path==='/'||path==='') return `${base}/`;
  return `${base}${path.startsWith('/')?path:`/${path}`}`;
}

type SeoInput={
  title:string;
  description:string;
  path:string;
};

export function buildMetadata({title,description,path}:SeoInput):Metadata{
  const canonical=absoluteUrl(path);
  return {
    title,
    description,
    alternates:{canonical},
    openGraph:{
      type:'website',
      locale:'ru_RU',
      siteName:SITE_NAME,
      title,
      description,
      url:canonical,
      images:[{url:absoluteUrl('/promsafe-logo-original.png'),alt:'Промбезопасность Консалт'}],
    },
    twitter:{card:'summary',title,description},
  };
}

